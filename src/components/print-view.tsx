import { breakdown } from "@/lib/budget";
import { addDays, formatCost, isoDate } from "@/lib/utils";
import { BUDGET_LABEL, type TripDTO } from "@/lib/schema";

/** Shown only when printing / saving as PDF: every day, no map, no buttons. */
export function PrintView({ trip }: { trip: TripDTO }) {
  const days = Array.from({ length: trip.durationDays }, (_, i) => i + 1);
  const total = breakdown(trip.items);

  return (
    <div className="hidden text-[12px] leading-snug text-black print:block">
      <h1 className="text-2xl font-semibold">{trip.destination}</h1>
      {trip.summary && <p className="mt-1">{trip.summary}</p>}
      <p className="mt-1 text-[11px] text-slate-600">
        {trip.durationDays} days from {trip.startDate} · {BUDGET_LABEL[trip.budget]} · ~{formatCost(total.total)} per person
        {trip.vibeTags.length ? ` · ${trip.vibeTags.join(", ")}` : ""}
        {trip.needs.length ? ` · Needs: ${trip.needs.join(", ")}` : ""}
        {trip.hiddenGems ? " · Hidden gems" : ""}
      </p>
      {trip.weatherSummary && <p className="text-[11px] text-slate-600">Weather when planned: {trip.weatherSummary}</p>}

      {days.map((d) => {
        const items = trip.items.filter((i) => i.dayNumber === d);
        const b = breakdown(items);
        const city = items[0]?.city;
        return (
          <section key={d} className="mt-4 break-inside-avoid">
            <h2 className="border-b pb-1 text-base font-semibold">
              Day {d} · {isoDate(addDays(new Date(`${trip.startDate}T00:00:00Z`), d - 1))}
              {city && trip.cities.length > 1 ? ` · ${city}` : ""}
            </h2>
            <table className="mt-1 w-full border-collapse">
              <tbody>
                {items.map((i) => (
                  <tr key={i.id} className="align-top">
                    <td className="w-12 py-1 pr-2 font-medium">{i.timeBadge}</td>
                    <td className="py-1 pr-2">
                      <span className="font-semibold">{i.title}</span>
                      {i.indoor ? " (indoor)" : ""}
                      <br />
                      {i.description}
                      {i.transitNote ? <span className="text-slate-600"> Getting there: {i.transitNote}.</span> : null}
                    </td>
                    <td className="w-14 py-1 text-right">{i.costInfo}</td>
                  </tr>
                ))}
              </tbody>
            </table>
            <p className="mt-1 text-[11px] text-slate-600">
              Day total ~{formatCost(b.total)} pp: food {formatCost(b.food)} · transport {formatCost(b.transport)} · activities{" "}
              {formatCost(b.activities)}
              {b.lodging ? ` · lodging ${formatCost(b.lodging)}` : ""}
            </p>
          </section>
        );
      })}

      {trip.packingList && (
        <section className="mt-5 break-inside-avoid">
          <h2 className="border-b pb-1 text-base font-semibold">Packing list</h2>
          {trip.packingList.categories.map((c) => (
            <div key={c.name} className="mt-1.5">
              <p className="font-semibold">{c.name}</p>
              <p>{c.items.map((i) => `☐ ${i.item}${i.note ? ` (${i.note})` : ""}`).join("   ")}</p>
            </div>
          ))}
        </section>
      )}
      <p className="mt-6 text-[10px] text-slate-500">Generated by Wayfarer AI. Places, prices and times are AI estimates: check before you go.</p>
    </div>
  );
}
